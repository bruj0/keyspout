#!/usr/bin/env python3
"""Lay a diagram's sibling subgraphs out vertically, by choosing, not guessing.

# Why

Several of the diagrams are wider than the content column. Mermaid lays a
diagram out with dagre, and dagre puts **sibling** subgraphs in a row, so a
diagram with four layers is four layers *side by side*. Narrowing it means
putting each layer below the one before.

# Why the previous script was replaced

It chained subgraphs with **arrows**: `Top --> Domain`. That is wrong in two
ways, and both had already happened.

* **It invented a dependency.** `Top --> Domain` asserts that the application
  layer depends on the domain crates. The author had written no such edge; the
  transformation added it, and the rendered diagram claimed it. A diagram is a
  statement about the system, so a layout constraint must never become a
  claim.
* **It needed a hand-written list of what to chain**, held in the script. One
  of the eight entries had already rotted: `components/ksp-cli.md` named a
  subgraph `CLI` that no longer exists, and the chain the script built from it
  added a **phantom node labelled `CLI`** to the rendered diagram. A list in
  the script is a second copy of a fact the diagram already states, so it can
  only drift.

It was also rigid in a third way: one rule was applied to every diagram even
though measurement says it is wrong for some. Forcing `direction TB` into the
subgraphs of the two-string diagram in `components/ksp-types.md` takes it from
315px wide to 581px - the script made a narrow diagram wider.

# What this script does

Two interventions, neither of which is an edge between the diagram's subjects:

* **`direction TB`** as the first line of a subgraph, so the layer's contents
  stack instead of spreading sideways;
* **an invisible link** `A ~~~ B` between consecutive subgraphs, in document
  order. Mermaid draws no line and no arrowhead for `~~~`, so the diagram
  claims nothing new, but dagre still has to order the two, which stacks them.

Order comes from the source, never from a list here. That is the order the
author wrote, so it is the reading order, and there is no second copy to keep
in step.

# How it chooses

Four candidates are built from the diagram as it stands, and each is
**rendered and measured**; the narrowest is kept, and a tie goes to the
candidate with fewer changes. That is the whole rule, and it is why the script
cannot make a diagram wider: a candidate that is wider simply loses.

    V0  as it stands
    V1  + direction TB inside each subgraph
    V2  + invisible links between consecutive subgraphs
    V3  + both

Rendering needs `mmdc`, which the site already requires - `check-mermaid.py`
uses the same renderer. Without it the script falls back to V0, which is a
no-op on a tree that is already stacked, so a clone without Chromium is not
left with a rewritten tree.

# What it never does

It never removes a subgraph, never reorders one, and never rewrites a line that
names a node or an edge. An earlier attempt dropped the `end` lines and
emptied five subgraphs; the diagrams still parsed and still rendered, and they
said nothing at all.

Bare `A --> B` arrows between two sibling subgraphs are rewritten to `A ~~~ B`.
That arrow is a dependency claim, and the `~~~` constrains the layout without
asserting anything.

# Usage

    scripts/site/stack-subgraphs.py              # rewrite; measure each choice
    scripts/site/stack-subgraphs.py --check      # fail if a rewrite is needed
    scripts/site/stack-subgraphs.py --no-measure # apply V3 without rendering
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
SITE = REPO / "site" / "docs"

# The reference section is generated by `prepare-docs.py` from the public tree
# on every build, so a rewrite here is thrown away. It is also the project's
# own prose, not the site's, and reshaping someone's diagram without asking is
# not this script's business.
GENERATED = "reference"

FENCE = "```mermaid"
END = "```"
BLOCK = re.compile(re.escape(FENCE) + r"\n(.*?)\n" + re.escape(END), re.DOTALL)

# The diagram kinds dagre lays out, so the only kinds `direction` and `~~~`
# mean anything to.
FLOW_KINDS = ("graph", "flowchart")

# A subgraph declaration with an id. The other forms - `subgraph "a label"`,
# a bare `subgraph` - carry no id to link to, so they are recognised only in
# order to be left alone.
SUBGRAPH_ANY = re.compile(r"^\s*subgraph\b")
SUBGRAPH_WITH_ID = re.compile(r"^(\s*)subgraph\s+([A-Za-z_]\w*)\s*(\[|$)")

# A bare, unlabelled arrow between two identifiers. `A -->|"label"| B` carries
# a claim and is never rewritten.
BARE_EDGE = re.compile(r"^\s*([A-Za-z_]\w*)\s*-->\s*([A-Za-z_]\w*)\s*$")

# A node given a shape, which is how the diagram declares one.
NODE_FORMS = re.compile(r"\b([A-Za-z_]\w*)\s*[\[({]")

# Any edge between two identifiers, whatever the arrow looks like. Used only
# to decide whether an identifier is declared somewhere, never to rewrite.
ANY_EDGE = re.compile(
    r"^\s*([A-Za-z_]\w*)\s*(?:-->|---|~~~|-\->|==>|--x|--o)",
    re.MULTILINE,
)

DIRECTION = re.compile(r"^\s*direction\s+(TB|TD|BT|LR|RL)\s*$")

INVISIBLE = "~~~"
INVISIBLE_EDGE = re.compile(
    r"^\s*([A-Za-z_]\w*)\s*" + re.escape(INVISIBLE) + r"\s*([A-Za-z_]\w*)\s*$"
)


def kind_of(body: str) -> str:
    """The diagram kind: the first word of the first non-blank line."""
    for line in body.split("\n"):
        stripped = line.strip()
        if not stripped or stripped.startswith("%%"):
            continue
        return stripped.split()[0]
    return ""


def subgraph_spans(lines: list[str]) -> list[tuple[int, int, str]]:
    """`(header index, closing index, id)` for every subgraph that has an id.

    The closing index is the `end` matching the `subgraph`, found by counting
    nesting depth. A subgraph without an id is skipped: there is nothing to
    link to, and building a link from a label is how the phantom node
    appeared.
    """
    spans: list[tuple[int, int, str]] = []
    depth = 0
    open_at: int | None = None
    open_id = ""
    for index, line in enumerate(lines):
        if SUBGRAPH_ANY.match(line):
            if depth == 0:
                match = SUBGRAPH_WITH_ID.match(line)
                open_at = index
                open_id = match.group(2) if match else ""
            depth += 1
            continue
        if line.strip() == "end" and depth:
            depth -= 1
            if depth == 0 and open_at is not None:
                if open_id:
                    spans.append((open_at, index, open_id))
                open_at = None
                open_id = ""
    return spans


def declared_ids(lines: list[str]) -> set[str]:
    """Every identifier the author actually declared.

    A node is declared by giving it a shape - `ID["label"]`, `ID("label")`,
    `ID{"label"}` - and a subgraph by its `subgraph ID` header. An identifier
    that appears *only* as the endpoint of a bare arrow has declared nothing:
    that arrow is what would create the node.

    This distinction is the whole check. Asking "is this id declared?" and
    accepting any appearance answers yes for the very line under suspicion,
    because naming an undeclared identifier is exactly what creates a node.
    So a bare arrow's endpoints are not evidence, and a shaped node's are.
    """
    ids: set[str] = set()
    subgraphs = {span[2] for span in subgraph_spans(lines)}
    for line in lines:
        header = SUBGRAPH_WITH_ID.match(line)
        if header:
            ids.add(header.group(2))
            continue
        if BARE_EDGE.match(line):
            # Whether these endpoints are declared is the question being
            # asked, so this line cannot answer it.
            continue
        for node in NODE_FORMS.finditer(line):
            ids.add(node.group(1))
        for edge in ANY_EDGE.finditer(line):
            ids.update(part for part in edge.groups() if part)
    ids.update(subgraphs)
    return ids


def drop_invented_edges(body: str, ids: list[str]) -> str:
    """Remove arrows the previous script invented between sibling subgraphs.

    Two shapes, both of which shipped and both of which the author never wrote.

    * **A dependency claim.** `Enrol --> Auth` says one layer depends on the
      next. `~~~` constrains the layout without asserting anything, so the
      arrow becomes `~~~`: same place in the layout, no claim.
    * **A phantom node.** `CLI --> Feature` names a subgraph `CLI` that no
      longer exists. Mermaid creates a node for an undeclared identifier, so
      the diagram grew a box nobody wrote. There is no `~~~` that fixes that,
      so the line goes.

    Splitting them matters: the first is recoverable and the second is not.
    """
    present = declared_ids(body.split("\n"))
    kept: list[str] = []
    for line in body.split("\n"):
        match = BARE_EDGE.match(line)
        if not match:
            kept.append(line)
            continue
        left, right = match.group(1), match.group(2)
        if left not in present or right not in present:
            # An endpoint this diagram never declares. A `CLI` node appeared
            # in `ksp-cli.md` exactly this way. `~~~` cannot repair it -
            # naming an undeclared id creates a node whatever the arrow - so
            # the only honest move is to drop the line.
            continue
        if left in ids or right in ids:
            # Two subgraphs, so this asserts a dependency between layers.
            kept.append(f"  {left} {INVISIBLE} {right}")
        else:
            kept.append(line)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(kept))


def add_directions(body: str) -> str:
    """Put `direction TB` first inside every subgraph that states no direction."""
    lines = body.split("\n")
    spans = subgraph_spans(lines)
    result = list(lines)
    offset = 0
    for header, close, _id in spans:
        inner = lines[header + 1 : close]
        if any(DIRECTION.match(line) for line in inner):
            continue
        indent = re.match(r"^(\s*)", lines[header]).group(1)
        result.insert(header + 1 + offset, f"{indent}    direction TB")
        offset += 1
    return "\n".join(result)


def add_links(body: str) -> str:
    """Join consecutive subgraphs, in document order, with an invisible link."""
    lines = body.split("\n")
    ids = [span[2] for span in subgraph_spans(lines)]
    if len(ids) < 2:
        return body

    present: set[frozenset[str]] = set()
    for line in lines:
        match = INVISIBLE_EDGE.match(line)
        if match:
            present.add(frozenset((match.group(1), match.group(2))))

    missing = [
        f"  {first} {INVISIBLE} {second}"
        for first, second in zip(ids, ids[1:])
        if frozenset((first, second)) not in present
    ]
    if not missing:
        return body
    return body.rstrip() + "\n" + "\n".join(missing)


def strip_directions(body: str) -> str:
    """Remove the `direction TB` hints the previous script inserted.

    Every `direction TB` in this tree came from that script; the author wrote
    none. So the line is a layout decision the script made, not a decision the
    author made, and a script whose whole point is to re-decide the layout has
    to be able to take it back out - otherwise the old answer is baked into
    every candidate and the narrower one can never be found.

    Only `TB` is stripped. The previous script only ever wrote `TB`, so any
    other direction is the author's and is left alone.
    """
    kept: list[str] = []
    for line in body.split("\n"):
        match = DIRECTION.match(line)
        if match and match.group(1) in ("TB", "TD"):
            continue
        kept.append(line)
    return "\n".join(kept)


def variants(body: str) -> list[tuple[str, str]]:
    """The layouts to choose between, all built from the *corrected* body.

    Two corrections happen first, and neither is up for measurement, because
    neither is a layout question:

    * **the invented arrows** go. An arrow between two sibling subgraphs is a
      dependency claim, and whether a claim is true is not something a width
      can settle. It becomes `~~~`, which occupies the same place in the
      layout and asserts nothing; where it named an id the diagram never
      declares, it is dropped, because it created a node nobody wrote.
    * **the previous script's `direction TB`** comes back out, so the hint is
      chosen rather than inherited.

    That leaves four layouts differing only in `direction TB` and the
    invisible links, which are both genuine layout questions with a
    measurable answer:

        as authored      neither
        directions       `direction TB` in each subgraph
        links            `~~~` between consecutive subgraphs
        both             both

    The four collapse to fewer when the corrections have already produced one
    of them - a diagram the previous script chained end to end already holds
    every link, so only the `direction TB` question is left open. Measuring
    the duplicates again would only confirm they are equal.
    """
    lines = body.split("\n")
    ids = [span[2] for span in subgraph_spans(lines)]
    base = strip_directions(drop_invented_edges(body, ids))
    with_directions = add_directions(base)

    names = ("as authored", "directions", "links", "directions and links")
    bodies = (base, with_directions, add_links(base), add_links(with_directions))

    # Identical bodies collapse to the cheapest name: `directions` and
    # `directions and links` are the same body when there is nothing to link.
    seen: dict[str, str] = {}
    for name, candidate in zip(names, bodies):
        seen.setdefault(candidate, name)
    return [(name, candidate) for candidate, name in seen.items()]


def measure(body: str, workdir: Path, tag: str) -> int | None:
    """Render `body` and return its intrinsic width, or `None` if it failed."""
    source = workdir / f"{tag}.mmd"
    svg = workdir / f"{tag}.svg"
    source.write_text(body, encoding="utf-8")
    if svg.exists():
        svg.unlink()

    subprocess.run(
        [MMDC, "--input", str(source), "--output", str(svg), "--quiet", *PUPPETEER],
        capture_output=True,
        text=True,
    )
    if not svg.exists() or svg.stat().st_size == 0:
        # An empty SVG with a zero exit code is what a Chromium launch
        # failure looks like. Treat it as no measurement, not as zero width.
        global _FAILED_RENDERS
        _FAILED_RENDERS += 1
        return None

    text = svg.read_text(encoding="utf-8", errors="replace")
    match = re.search(r'<svg[^>]*\bviewBox="[^"]*?([0-9.]+)\s+([0-9.]+)"', text)
    if not match:
        return None
    return round(float(match.group(1)))


MMDC = shutil.which("mmdc")

# Set by `--puppeteer-config`. Chromium refuses to start its sandbox when the
# process is root, which a CI runner is, so without this every render fails and
# every measurement is `None` - and a check that measures nothing passes.
PUPPETEER: list[str] = []

# How much narrower a candidate must be to displace the current layout.
#
# Measurement is exact on one machine, but a renderer upgrade can move a width
# by a pixel or two. Without a margin the choice could flip between "as
# authored" and "directions" on a renderer change and turn a green build red
# for a reason no one changed. Percent, so it scales with the diagram.
TOLERANCE_PERCENT = 2.0

# Renders that produced no SVG, counted so `--check` can refuse to pass on the
# strength of measurements that never happened.
_FAILED_RENDERS = 0


def choose(body: str, workdir: Path, tag: str) -> str:
    """The narrowest layout, measured.

    Measured, not guessed, because the four layouts do not order the same way
    on every diagram: forcing `direction TB` takes `components/ksp-types.md`'s
    two-string diagram from 315px to 581px, and takes
    `components/ksp-cli.md`'s wide one from 2509px to 862px. One rule cannot
    be right for both, so nothing here assumes which it is.

    A candidate has to be narrower by `TOLERANCE_PERCENT` to win, so a
    renderer's pixel-level sway cannot flip the choice. Ties, and anything
    inside the margin, go to the earlier candidate - the one that changes
    least.
    """
    options = variants(body)
    if len(options) == 1:
        return options[0][1]

    best = options[0][1]
    best_width = measure(best, workdir, f"{tag}-0")
    if best_width is None:
        # Nothing measured: return the correction, which is required, and
        # leave the layout as the author wrote it.
        return best

    def beats(candidate: int, current: int) -> bool:
        return candidate < current * (1.0 - TOLERANCE_PERCENT / 100.0)

    for index, (_name, candidate) in enumerate(options[1:], 1):
        width = measure(candidate, workdir, f"{tag}-{index}")
        if width is None:
            continue
        if beats(width, best_width):
            best_width = width
            best = candidate

    return best


def rewrite(body: str, tag: str, measure_it: bool) -> str:
    """The body this script would keep for one diagram.

    A diagram that is not a `graph` or a `flowchart` is left alone: dagre did
    not lay it out, so `direction` and `~~~` mean nothing to it and adding
    them would only be noise. A flow diagram with fewer than two subgraphs
    that have ids has nothing to stack against, so only the invented arrows
    are removed.
    """
    if kind_of(body).lower() not in FLOW_KINDS:
        return body

    lines = body.split("\n")
    ids = [span[2] for span in subgraph_spans(lines)]

    if len(ids) < 2:
        return drop_invented_edges(body, ids)

    if not measure_it:
        # `--no-measure`: take the fullest layout and let the checker see it.
        return variants(body)[-1][1]

    with tempfile.TemporaryDirectory() as directory:
        return choose(body, Path(directory), tag)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Lay sibling subgraphs out vertically by choosing, not guessing."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail if a rewrite is needed. Writes nothing.",
    )
    parser.add_argument(
        "--no-measure",
        action="store_true",
        help="Apply the fullest transformation without rendering to compare.",
    )
    parser.add_argument(
        "--puppeteer-config",
        type=Path,
        default=None,
        metavar="FILE",
        help="Chromium flags for `mmdc`. Required as root; see site/puppeteer.json.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=SITE,
        help=f"The documentation tree to read. Default: {SITE}",
    )
    args = parser.parse_args(argv)

    if not args.root.is_dir():
        print(f"error: {args.root} is not a directory", file=sys.stderr)
        return 1

    if MMDC is None and not args.no_measure:
        print(
            "warning: `mmdc` is not on PATH, so no layout can be measured and\n"
            "         each diagram is left as it is. Install it with\n"
            "         `npm install --global @mermaid-js/mermaid-cli` to let this\n"
            "         script choose.",
            file=sys.stderr,
        )

    if args.puppeteer_config is not None:
        PUPPETEER.extend(["--puppeteerConfigFile", str(args.puppeteer_config)])

    measure_it = not args.no_measure and MMDC is not None
    changed: list[str] = []

    for path in sorted(args.root.rglob("*.md")):
        if GENERATED in path.relative_to(args.root).parts:
            continue
        text = path.read_text(encoding="utf-8")
        if FENCE not in text:
            continue

        pieces: list[str] = []
        cursor = 0
        touched = False

        for number, match in enumerate(BLOCK.finditer(text), 1):
            body = match.group(1)
            stacked = rewrite(
                body,
                tag=f"{path.stem}-{number}",
                measure_it=measure_it,
            )

            pieces.append(text[cursor : match.start()])
            pieces.append(f"{FENCE}\n{stacked}\n{END}")
            cursor = match.end()
            if stacked != body:
                touched = True
        pieces.append(text[cursor:])

        if not touched:
            continue

        updated = "".join(pieces)
        if updated == text:
            continue

        changed.append(str(path.relative_to(args.root)))
        if not args.check:
            path.write_text(updated, encoding="utf-8")

    if args.check:
        if measure_it and _FAILED_RENDERS and not changed:
            # Passing here would be the trap this repository has already paid
            # for: a gate that measured nothing and called the tree green.
            print(
                f"error: {_FAILED_RENDERS} render(s) produced no SVG, so no layout\n"
                "       was measured. A check that measures nothing cannot pass.\n"
                "       As root, pass --puppeteer-config site/puppeteer.json;\n"
                "       Chromium will not start its sandbox there.",
                file=sys.stderr,
            )
            return 1
        if changed:
            print(
                f"error: {len(changed)} file(s) hold a diagram that is not stacked:",
                file=sys.stderr,
            )
            for name in changed:
                print(f"  {name}", file=sys.stderr)
            print(
                "\nrun `scripts/site/stack-subgraphs.py` to rewrite them.",
                file=sys.stderr,
            )
            return 1
        print("every diagram with sibling subgraphs is stacked")
        return 0

    print(f"updated {len(changed)} file(s)")
    for name in changed:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
